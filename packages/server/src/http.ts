/**
 * HTTP helpers shared by the REST routes: pt-BR errors and small input validators (no schema lib).
 */

import type { ApiErrorBody } from '@gt7/shared';
import type { FastifyReply } from 'fastify';

/** Error thrown by route handlers; mapped to `{ error: { code, message } }` with `status`. */
export class HttpError extends Error {
  constructor(
    readonly status: number,
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'HttpError';
  }
}

export const badRequest = (message: string, code = 'invalidInput') =>
  new HttpError(400, code, message);
export const notFound = (message: string, code = 'notFound') => new HttpError(404, code, message);
export const conflict = (message: string, code = 'conflict') => new HttpError(409, code, message);

export function sendError(reply: FastifyReply, status: number, code: string, message: string) {
  const body: ApiErrorBody = { error: { code, message } };
  return reply.code(status).type('application/json; charset=utf-8').send(body);
}

// ---------------------------------------------------------------------------------------------
// Validators (throw HttpError 400 with a pt-BR message)
// ---------------------------------------------------------------------------------------------

export type Obj = Record<string, unknown>;

export function bodyObject(body: unknown): Obj {
  if (typeof body !== 'object' || body === null || Array.isArray(body)) {
    throw badRequest('O corpo da requisição deve ser um objeto JSON.');
  }
  return body as Obj;
}

export function optString(o: Obj, key: string, label: string, max = 200): string | undefined {
  const v = o[key];
  if (v === undefined) return undefined;
  if (typeof v !== 'string') throw badRequest(`O campo "${label}" deve ser um texto.`);
  if (v.length > max) throw badRequest(`O campo "${label}" pode ter no máximo ${max} caracteres.`);
  return v;
}

export function reqString(o: Obj, key: string, label: string, max = 200): string {
  const v = optString(o, key, label, max);
  if (v === undefined || !v.trim()) throw badRequest(`Informe o campo "${label}".`);
  return v.trim();
}

/** Optional nullable string: undefined = absent, null = clear. */
export function optNullableString(
  o: Obj,
  key: string,
  label: string,
  max = 200,
): string | null | undefined {
  if (o[key] === null) return null;
  return optString(o, key, label, max);
}

export function optBoolean(o: Obj, key: string, label: string): boolean | undefined {
  const v = o[key];
  if (v === undefined) return undefined;
  if (typeof v !== 'boolean') throw badRequest(`O campo "${label}" deve ser true ou false.`);
  return v;
}

export function optNumber(
  o: Obj,
  key: string,
  label: string,
  range: { min?: number; max?: number; integer?: boolean } = {},
): number | undefined {
  const v = o[key];
  if (v === undefined || v === null) return undefined;
  if (typeof v !== 'number' || !Number.isFinite(v)) {
    throw badRequest(`O campo "${label}" deve ser um número.`);
  }
  if (range.integer && !Number.isInteger(v)) {
    throw badRequest(`O campo "${label}" deve ser um número inteiro.`);
  }
  if (range.min !== undefined && v < range.min) {
    throw badRequest(`O campo "${label}" deve ser no mínimo ${range.min}.`);
  }
  if (range.max !== undefined && v > range.max) {
    throw badRequest(`O campo "${label}" deve ser no máximo ${range.max}.`);
  }
  return v;
}

/** Parses an integer query parameter. */
export function queryInt(
  q: Obj,
  key: string,
  label: string,
  range: { min?: number; max?: number } = {},
): number | undefined {
  const raw = q[key];
  if (raw === undefined || raw === '') return undefined;
  const n = typeof raw === 'string' ? Number(raw) : Number.NaN;
  if (!Number.isInteger(n)) throw badRequest(`O parâmetro "${label}" deve ser um número inteiro.`);
  if (range.min !== undefined && n < range.min) {
    throw badRequest(`O parâmetro "${label}" deve ser no mínimo ${range.min}.`);
  }
  if (range.max !== undefined && n > range.max) {
    throw badRequest(`O parâmetro "${label}" deve ser no máximo ${range.max}.`);
  }
  return n;
}

export function queryBool(q: Obj, key: string): boolean | undefined {
  const raw = q[key];
  if (raw === undefined || raw === '') return undefined;
  if (raw === '1' || raw === 'true') return true;
  if (raw === '0' || raw === 'false') return false;
  throw badRequest(`O parâmetro "${key}" deve ser true ou false.`);
}

export function queryString(q: Obj, key: string): string | undefined {
  const raw = q[key];
  return typeof raw === 'string' && raw !== '' ? raw : undefined;
}

const IPV4 = /^(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)(\.(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)){3}$/;

export function isIPv4(s: string): boolean {
  return IPV4.test(s);
}

/** Ids generated by core are short opaque strings; reject anything path-like. */
export function isSafeId(s: string): boolean {
  return /^[A-Za-z0-9_.:-]{1,128}$/.test(s) && !s.includes('..');
}
