#!/usr/bin/env node
/**
 * Regenerates packages/shared/src/cars/data.ts from the community database ddm999/gt7info
 * (MIT-0, data extracted from the game): _data/db/{cars,maker,country,cargrp}.csv.
 *
 *   node packages/shared/scripts/gen-cars.mjs                 # downloads from GitHub (pinned commit)
 *   node packages/shared/scripts/gen-cars.mjs --ref web-new   # latest of the branch
 *   node packages/shared/scripts/gen-cars.mjs --from <dir>    # local folder with the 4 CSV files
 *
 * The app NEVER downloads anything at run time: this script only exists to refresh the committed
 * data file. After running, run `biome format --write` on the generated file and the tests.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PINNED_REF = '2648c847f1021be69b67430e65e2246098383e66';
const REPO = 'ddm999/gt7info';
const FILES = ['cars', 'maker', 'country', 'cargrp'];

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const ref = opt('--ref') ?? PINNED_REF;
const fromDir = opt('--from');

async function load(name) {
  if (fromDir) return readFileSync(join(fromDir, `${name}.csv`), 'utf8');
  const url = `https://raw.githubusercontent.com/${REPO}/${ref}/_data/db/${name}.csv`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

/** Rows of a simple CSV (no quoting in these files: names never contain commas). */
function rows(text) {
  return text
    .replace(/\r/g, '')
    .split('\n')
    .filter((l) => l.trim() !== '')
    .slice(1)
    .map((l) => l.split(','));
}

function slugify(name) {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' e ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** "A110 '17" -> 2017. Two digits: up to '26 = 20xx, from '27 = 19xx (oldest GT7 car is 1929). */
function yearOf(name) {
  const m = / '(\d\d)$/.exec(name);
  if (!m) return null;
  const yy = Number(m[1]);
  return yy <= 26 ? 2000 + yy : 1900 + yy;
}

const text = Object.fromEntries(await Promise.all(FILES.map(async (f) => [f, await load(f)])));

const countries = new Map(rows(text.country).map(([id, , code]) => [Number(id), code]));
const groups = new Map(rows(text.cargrp).map(([id, g]) => [Number(id), g]));
const makers = rows(text.maker)
  .map(([id, name, country]) => ({
    id: Number(id),
    name,
    country: countries.get(Number(country)) ?? 'pdi',
    slug: slugify(name),
  }))
  .sort((a, b) => a.id - b.id);
const cars = rows(text.cars)
  .map(([id, name, maker]) => ({
    id: Number(id),
    name,
    maker: Number(maker),
    group: groups.get(Number(id)) ?? null,
    year: yearOf(name),
  }))
  .sort((a, b) => a.id - b.id);

// Sanity checks: refuse to write inconsistent data.
const makerIds = new Set(makers.map((m) => m.id));
if (new Set(cars.map((c) => c.id)).size !== cars.length) throw new Error('duplicate car ids');
if (new Set(makers.map((m) => m.slug)).size !== makers.length) throw new Error('duplicate slugs');
for (const c of cars) if (!makerIds.has(c.maker)) throw new Error(`car ${c.id}: unknown maker`);
if (cars.length < 400) throw new Error(`only ${cars.length} cars: source looks truncated`);

const q = (s) => JSON.stringify(s);
const out = `// GENERATED by packages/shared/scripts/gen-cars.mjs. Do not edit by hand.
// Source: https://github.com/${REPO} (_data/db/{cars,maker,country,cargrp}.csv), license MIT-0,
// commit ${ref}, collected on ${new Date().toISOString().slice(0, 10)}.
// Facts only: GT7 car id (= telemetry carCode), official English name, maker, group and year.

/** Where the data came from (shown in the docs and tests). */
export const CARS_SOURCE = {
  repo: ${q(`https://github.com/${REPO}`)},
  ref: ${q(ref)},
  license: 'MIT-0',
  collectedAt: ${q(new Date().toISOString().slice(0, 10))},
} as const;

/** [id, name, countryCode, slug]. */
export const MAKERS_DATA: readonly (readonly [number, string, string, string])[] = [
${makers.map((m) => `  [${m.id}, ${q(m.name)}, ${q(m.country)}, ${q(m.slug)}],`).join('\n')}
];

/** [id (= carCode), official name, makerId, group ('1'|'2'|'3'|'4'|'B'|'N'|'X'|null), year|null]. */
export const CARS_DATA: readonly (readonly [number, string, number, string | null, number | null])[] =
  [
${cars.map((c) => `    [${c.id}, ${q(c.name)}, ${c.maker}, ${q(c.group)}, ${c.year}],`).join('\n')}
  ];
`;
const target = fileURLToPath(new URL('../src/cars/data.ts', import.meta.url));
writeFileSync(target, out);
console.log(`${cars.length} cars, ${makers.length} makers -> ${target}`);
