/** A widget placed on the custom grid (cell units, origin top-left). */
export interface WidgetPlacement {
  /** Unique within the layout (same widget may appear twice). */
  key: string;
  widget: WidgetId;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Widget-specific options (e.g. units). */
  options?: Record<string, string | number | boolean>;
}

export interface WidgetGridLayout {
  columns: number;
  rows: number;
  items: WidgetPlacement[];
}

/** Per-device dashboard configuration, stored on the server. */
export interface DeviceProfile {
  /** Random id generated by the browser and kept in localStorage. */
  deviceId: string;
  /** Friendly name ("Celular", "PC"). */
  name: string;
  /** Enabled views in carousel order. */
  views: ViewId[];
  startView: ViewId;
  /** Gesture lock (prevents accidental view changes). */
  locked: boolean;
  /** Lap-completed pop-up cards. */
  popupsEnabled: boolean;
  /** Preferred delta reference for this device. */
  deltaReference: DeltaReferenceKind;
  /** Ask which track the driver will drive when the game goes to the menu (spec 06; default on). */
  askTrackOnStart: boolean;
  customLayout: WidgetGridLayout;
  updatedAt: number;
}

