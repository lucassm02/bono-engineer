export function createDefaultDeviceProfile(deviceId: string, name = 'Dispositivo'): DeviceProfile {
  return {
    deviceId,
    name,
    views: ['corrida', 'deltaGrande', 'pneus', 'inputs', 'motor'],
    startView: 'corrida',
    locked: false,
    popupsEnabled: true,
    deltaReference: 'personalBest',
    customLayout: {
      ...DEFAULT_CUSTOM_LAYOUT,
      items: DEFAULT_CUSTOM_LAYOUT.items.map((i) => ({ ...i })),
    },
    updatedAt: 0,
  };
}
