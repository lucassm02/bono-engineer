#!/usr/bin/env node
/**
 * Regenerates packages/web/src/brands/brandIcons.ts: the single-path SVG logos (24x24) of the
 * car makers that exist in the `simple-icons` package (devDependency; icon files are CC0-1.0).
 *
 *   node packages/web/scripts/gen-brand-icons.mjs
 *
 * Only the path data is copied into the TS module, so the app has NO runtime dependency on the
 * package. Makers that are not in simple-icons are not listed here: the UI draws a monogram badge.
 * Logos are trademarks of their owners and are used only to identify the maker.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Maker slug (shared/src/cars/data.ts) -> simple-icons slug. */
const MAP = {
  'aston-martin': 'astonmartin',
  audi: 'audi',
  bmw: 'bmw',
  chevrolet: 'chevrolet',
  citroen: 'citroen',
  fiat: 'fiat',
  ford: 'ford',
  honda: 'honda',
  hyundai: 'hyundai',
  mazda: 'mazda',
  mitsubishi: 'mitsubishi',
  nissan: 'nissan',
  peugeot: 'peugeot',
  renault: 'renault',
  subaru: 'subaru',
  suzuki: 'suzuki',
  toyota: 'toyota',
  volkswagen: 'volkswagen',
  infiniti: 'infiniti',
  mini: 'mini',
  volvo: 'volvo',
  ferrari: 'ferrari',
  lamborghini: 'lamborghini',
  bugatti: 'bugatti',
  maserati: 'maserati',
  mclaren: 'mclaren',
  tesla: 'tesla',
  ktm: 'ktm',
  porsche: 'porsche',
  jeep: 'jeep',
  amg: 'amg',
  'ds-automobiles': 'dsautomobiles',
  skoda: 'skoda',
  opel: 'opel',
  polestar: 'polestar',
  xiaomi: 'xiaomi',
};

const candidates = ['../../../node_modules/simple-icons', '../node_modules/simple-icons'];
const pkgDir = candidates
  .map((c) => fileURLToPath(new URL(c, import.meta.url)))
  .find((d) => existsSync(join(d, 'package.json')));
if (!pkgDir) throw new Error('simple-icons is not installed (npm install)');
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const meta = JSON.parse(readFileSync(join(pkgDir, 'data', 'simple-icons.json'), 'utf8'));
const titleOf = new Map(meta.map((i) => [i.slug ?? i.title.toLowerCase(), i.title]));

const q = (s) => JSON.stringify(s);
const lines = [];
for (const [maker, icon] of Object.entries(MAP)) {
  const svg = readFileSync(join(pkgDir, 'icons', `${icon}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${icon}: expected exactly 1 path, got ${paths.length}`);
  lines.push(`  ${q(maker)}: { title: ${q(titleOf.get(icon) ?? icon)}, d: ${q(paths[0])} },`);
}

const out = `// GENERATED by packages/web/scripts/gen-brand-icons.mjs from simple-icons ${pkg.version} (CC0-1.0).
// Brand logos are trademarks of their owners and are used here only to identify the maker.

/** Maker slug -> single-path logo, 24x24 viewBox, to be filled with currentColor. */
export const BRAND_ICONS: Readonly<Record<string, { title: string; d: string }>> = {
${lines.join('\n')}
};
`;
const target = fileURLToPath(new URL('../src/brands/brandIcons.ts', import.meta.url));
writeFileSync(target, out);
console.log(`${lines.length} logos (simple-icons ${pkg.version}) -> ${target}`);
